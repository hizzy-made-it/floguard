def test_v1_stays_default_and_unchanged(pg):
    assert pg("select fsi_model_version()") == "v1"
    pg("insert into parcel_risk (parcel_id, lat, lon, twi_n, hand_n, depr_n, hsg, fema_zone) values "
       "('a', 29.03, -81.07, 0.7, 0.2, 0.5, 'A/D', 'X'), ('b', 29.10, -81.20, 0.1, 0.9, 0, 'A', 'AE')")
    pg("update parcel_risk set terrain_v2_at = now(), twi_v2_n = 0.9, hand_v2_n = 0.1, depr_v2_n = 0.9, "
       "nbr_rel_m = -0.5 where parcel_id = 'a'")
    for b in range(8):
        pg(f"select fsi_static_batch({b})")
    rows = pg("select parcel_id, fsi_static = fsi_static_expr(twi_n, hand_n, depr_n, hsg, fema_zone), model_version, "
              "fsi_static_v2 is not null from parcel_risk order by 1")
    assert rows.splitlines() == ["a|t|v1|t", "b|t|v1|f"]


def test_v2_expression_matches_python(pg):
    rng = random.Random(7)
    zones = ["X", "X-SHADED", "AE", "AO", None]
    dcs = ["Very poorly drained", "Poorly drained", "Well drained", "Excessively drained", None, "Unknown class"]
    cases = []
    for _ in range(300):
        cases.append([rng.choice([None, round(rng.uniform(-0.2, 1.2), 4)]),
                      rng.choice([None, round(rng.uniform(-0.2, 1.2), 4)]),
                      rng.choice([None, round(rng.uniform(0, 1), 4)]),
                      rng.choice([None, round(rng.uniform(-1, 1), 3)]),
                      rng.choice([None, round(rng.uniform(-1, 1), 3)]),
                      rng.choice(["A", "B", "C", "D", None]), rng.choice(dcs),
                      rng.choice([None, 0.0, round(rng.uniform(0.1, 300), 3)]),
                      rng.choice([None, round(rng.uniform(0, 2.5), 3)]), rng.choice(zones)])

    def lit(v, typ):
        if v is None:
            return f"null::{typ}"
        return f"'{v}'::{typ}" if typ == "text" else f"{v}::{typ}"
    types = ["real"] * 5 + ["text", "text", "real", "real", "text"]
    sql = " union all ".join(
        f"select {i}, fsi_static_v2_expr({', '.join(lit(v, t) for v, t in zip(c, types))})"
        for i, c in enumerate(cases))
    got = {int(a): float(b) for a, b in (l.split("|") for l in pg(sql).splitlines())}
    for i, c in enumerate(cases):
        # SQL works in float4 for real args; allow rounding at the 4th decimal
        assert got[i] == pytest.approx(C2.static_score_v2(*c), abs=2e-4), (c, got[i])


def test_apply_switch_and_rollback(pg):
    rows = [{"parcel_id": "b", "huc12": "030802010101", "dem_res_m": 1, "dem_1m_frac": 1.0, "geom_mode": "polygon",
             "yard_only": True, "lot_area_m2": 900.5, "elev_p10_m": 4.1, "elev_med_m": 4.3, "twi_max": 9.1,
             "twi_awm": 7.2, "twi_v2_n": 0.4, "hand_min_m": -0.2, "hand_v2_n": 0.1, "depr_max_m": 0.3,
             "depr_frac": 0.5, "depr_v2_n": 0.38, "nbr_rel_m": -0.2, "nbr_count": 6, "street_rel_m": -0.3,
             "hsg_eff": "D", "hsg_dual": True, "drain_class": "Poorly drained", "ksat_um_s": 92,
             "wt_depth_m": 0.0, "soil_cov": 1.0, "fsi_confidence": 0.91, "fsi_inputs": {"dem": "3dep_1m"}}]
    assert pg(f"select terrain_v2_apply('{json.dumps(rows)}'::jsonb)") == "1"
    v1_b = float(pg("select fsi_static from parcel_risk where parcel_id = 'b'"))
    s2 = float(pg("select fsi_static_v2 from parcel_risk where parcel_id = 'b'"))
    assert s2 == pytest.approx(C2.static_score_v2(0.4, 0.1, 0.38, -0.2, -0.3, "D", "Poorly drained", 92, 0.0, "AE"), abs=2e-4)
    assert pg("select fsi_set_model_version('v2')") == "v2"
    for b in range(8):
        pg(f"select fsi_static_batch({b})")
    assert pg("select fsi_static = fsi_static_v2, model_version from parcel_risk where parcel_id = 'b'") == "t|v2"
    pg("insert into parcel_risk (parcel_id, twi_n, hsg) values ('c', 0.5, 'C')")
    pg("select fsi_static_batch(b) from generate_series(0, 7) b")
    assert pg("select model_version from parcel_risk where parcel_id = 'c'") == "v1"   # no v2 terms -> v1
    pg("select fsi_set_model_version('v1')")
    pg("select fsi_static_batch(b) from generate_series(0, 7) b")
    assert float(pg("select fsi_static from parcel_risk where parcel_id = 'b'")) == pytest.approx(v1_b)
    with pytest.raises(AssertionError):
        pg("select fsi_set_model_version('v3')")
    assert pg("select fsi_recompute_static()::jsonb->>'model_version'") == "v1"


def test_mrms_ids_match_python(pg):
    rng = random.Random(3)
    pts = [(round(rng.uniform(28.6, 29.5), 6), round(rng.uniform(-81.7, -80.7), 6)) for _ in range(300)]
    pts += [(29.0, -81.0), (29.005, -81.005), (28.99, -80.99)]
    sql = " union all ".join(f"select {i}, mrms_cell_id({la}, {lo})" for i, (la, lo) in enumerate(pts))
    got = dict(l.split("|") for l in pg(sql).splitlines())
    for i, (la, lo) in enumerate(pts):
        assert got[str(i)] == R.mrms_cell_id(*R.mrms_index(la, lo))
    n = int(pg("select mrms_cells_seed()"))
    assert n >= 1
    assert pg("select count(*) from rainfall_cell where source = 'mrms' and cell_id like 'm%'") == str(n)
    pg("select rain_source_use('mrms', b) from generate_series(0, 7) b")
    assert pg("select count(*) from parcel_risk where lat is not null and rain_cell <> mrms_cell") == "0"
    pg("select rain_source_use('open_meteo', b) from generate_series(0, 7) b")
    assert pg("select rain_cell from parcel_risk where parcel_id = 'a'") == "580_-1622"


