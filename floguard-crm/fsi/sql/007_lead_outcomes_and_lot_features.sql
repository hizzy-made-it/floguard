create or replace function public.touch_updated_at()
returns trigger language plpgsql
as $$ begin new.updated_at := now(); return new; end $$;

create or replace function public.lead_outcomes_snapshot()
returns trigger
language plpgsql security definer
set search_path = public
as $$
declare
  p public.parcel_risk%rowtype;
  rs public.rainfall_state%rowtype;
begin
  new.updated_at := now();
  if new.parcel_id is not null then
    select * into p from public.parcel_risk where parcel_id = new.parcel_id;
    if found then
      new.fsi_live_at        := p.fsi_live;
      new.fsi_static_at      := p.fsi_static;
      new.must_have_score_at := p.must_have_score;
      new.must_have_band_at  := p.must_have_band;
      new.fema_zone_at       := p.fema_zone;
      new.hsg_at             := p.hsg;
      new.claim_heat_at      := p.claim_heat;
      new.twi_n_at           := p.twi_n;
      new.hand_n_at          := p.hand_n;
      if new.address is null then new.address := p.address; end if;
      if new.city is null then new.city := p.city; end if;
      if new.zip is null then new.zip := p.zip; end if;
    end if;
  end if;
  select * into rs from public.rainfall_state where county_fips = '12127';
  if found then
    new.rain_24h_at := rs.rain_24h;
    new.api_at      := rs.api_value;
  end if;
  return new;
end;
$$;

drop trigger if exists lead_outcomes_snapshot_trg on public.lead_outcomes;
create trigger lead_outcomes_snapshot_trg before insert on public.lead_outcomes
  for each row execute function public.lead_outcomes_snapshot();
drop trigger if exists lead_outcomes_touch_trg on public.lead_outcomes;
create trigger lead_outcomes_touch_trg before update on public.lead_outcomes
  for each row execute function public.touch_updated_at();

create or replace function public.lead_outcomes_readiness()
returns table(outcomes bigint, won bigint, lost bigint, no_show bigint, water_assessed bigint,
              water_yes bigint, water_no bigint, with_parcel bigint,
              ready_p_close boolean, ready_p_water boolean)
language sql stable security definer
set search_path = public
as $$
  select
    count(*),
    count(*) filter (where outcome = 'won'),
    count(*) filter (where outcome = 'lost'),
    count(*) filter (where outcome = 'no_show'),
    count(*) filter (where water_confirmed is not null),
    count(*) filter (where water_confirmed),
    count(*) filter (where water_confirmed = false),
    count(*) filter (where parcel_id is not null),
    count(*) filter (where parcel_id is not null and outcome in ('won','lost')) >= 100
      and count(*) filter (where parcel_id is not null and outcome = 'won') >= 30,
    count(*) filter (where parcel_id is not null and water_confirmed is not null) >= 100
      and least(count(*) filter (where parcel_id is not null and water_confirmed),
                count(*) filter (where parcel_id is not null and water_confirmed = false)) >= 30
  from public.lead_outcomes
$$;

