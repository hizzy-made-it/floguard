-- A. lead_outcomes — the calibration label stream (spec §3 "back-fit against
--    closed jobs"). One row per lead once a rep knows the result. The BEFORE
--    INSERT trigger freezes the parcel's model inputs at that moment so later
--    rescoring never rewrites history.
--    lead_outcomes_readiness() says when there is enough to fit weights
--    (>=100 won/lost with parcel, >=30 won; or >=100 water yes/no, >=30 each).
-- ---------------------------------------------------------------------------
create table if not exists public.lead_outcomes (
  id                 bigint generated by default as identity primary key,
  lead_key           text not null,          -- stable key from the CRM lead store
  lead_id            text,
  parcel_id          text,
  address            text,
  city               text,
  zip                text,
  outcome            text not null check (outcome in ('won', 'lost', 'no_show')),
  amount             numeric,
  package            text,
  lost_reason        text,
  water_confirmed    boolean,                -- rep saw water on site (the second label)
  water_where        text[] not null default '{}',
  water_depth_in     real,
  water_last_seen    date,
  assessed_at        date,
  rep                text,
  notes              text,
  -- snapshot of model inputs at insert time
  fsi_live_at        real,
  fsi_static_at      real,
  must_have_score_at real,
  must_have_band_at  text,
  fema_zone_at       text,
  hsg_at             text,
  claim_heat_at      real,
  twi_n_at           real,
  hand_n_at          real,
  rain_24h_at        real,
  api_at             real,
  source             text not null default 'crm',
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now()
);
create unique index if not exists lead_outcomes_lead_key_uidx on public.lead_outcomes (lead_key);
create index if not exists lead_outcomes_parcel_idx on public.lead_outcomes (parcel_id);
create index if not exists lead_outcomes_created_idx on public.lead_outcomes (created_at desc);
