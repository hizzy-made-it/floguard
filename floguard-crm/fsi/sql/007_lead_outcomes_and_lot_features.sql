create or replace function public.lot_features_from_arcgis(content jsonb)
returns jsonb
language sql immutable
as $$
  with a as (
    select f->'attributes' as x from jsonb_array_elements(content->'features') f
  ), r as (
    select
      nullif(trim(x->>'PARID'), '') as parcel_id,
      coalesce(
        nullif((x->>'LANDSQFT')::double precision, 0),
        nullif((x->>'CALCACRES')::double precision, 0) * 43560,
        nullif((x->>'LANDACRES')::double precision, 0) * 43560) as lot_sqft,
      coalesce(nullif((x->>'RES_MAX_STORIES')::double precision, 0), nullif((x->>'COM_MAX_STORIES')::double precision, 0)) as stories,
      nullif(coalesce((x->>'BLDGCOUNT')::double precision, 0) + coalesce((x->>'COM_BLDGCOUNT')::double precision, 0), 0) as bldg_count,
      nullif((x->>'LIVUNIT')::double precision, 0) as living_units,
      nullif((x->>'COM_TOTALAREA')::double precision, 0) as com_area,
      nullif((x->>'IMPRJUST')::double precision, 0) as impr_just,
      nullif((x->>'LANDJUST')::double precision, 0) as land_just
    from a
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'parcel_id', parcel_id,
    'lot_sqft', case when lot_sqft > 0 then round(lot_sqft) end,
    'stories', case when stories > 0 then round(stories::numeric, 1) end,
    'bldg_count', case when bldg_count > 0 then round(bldg_count) end,
    'living_units', case when living_units > 0 then round(living_units) end,
    'com_area', case when com_area > 0 then com_area end,
    'impr_just', case when impr_just > 0 then impr_just end,
    'land_just', case when land_just > 0 then land_just end)), '[]'::jsonb)
  from r where parcel_id is not null
$$;

create or replace function public.lot_features_apply(rows jsonb)
returns integer
language plpgsql security definer
set search_path = public
as $$
declare n integer;
begin
  update public.parcel_risk p
     set lot_sqft     = v.lot_sqft,
         stories      = v.stories,
         bldg_count   = v.bldg_count,
         living_units = v.living_units,
         com_area     = v.com_area,
         impr_just    = v.impr_just,
         land_just    = v.land_just,
         lot_features_at = now()
    from jsonb_to_recordset(rows) as v(
      parcel_id text, lot_sqft real, stories real, bldg_count int,
      living_units int, com_area real, impr_just real, land_just real)
   where p.parcel_id = v.parcel_id;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- footprint ≈ conditioned area / stories; impervious ≈ footprint / lot.
create or replace function public.lot_features_derive()
returns integer
language plpgsql security definer
set search_path = public
set statement_timeout = '600s'
as $$
declare n integer;
begin
  update public.parcel_risk
     set footprint_sqft = f.footprint,
         impervious_ratio = case
           when f.footprint is not null and lot_sqft > 0
             then least(1.0, f.footprint / lot_sqft)
           else null end
    from (
      select parcel_id,
             case
               when coalesce(living_area, 0) > 0 then living_area / greatest(coalesce(stories, 1), 1)
               when coalesce(com_area, 0) > 0    then com_area   / greatest(coalesce(stories, 1), 1)
               else null end as footprint
        from public.parcel_risk
       where lot_features_at is not null
    ) f
   where f.parcel_id = parcel_risk.parcel_id;
  get diagnostics n = row_count;
  return n;
end;
$$;

-- Queue N pages of the appraiser layer via pg_net, then drain with lot_enrich_process().
--   select lot_enrich_enqueue(0, 320, 1000);   -- ~312k parcels
--   select * from lot_enrich_process(50);      -- repeat until pending = 0
--   select lot_features_derive();
create or replace function public.lot_enrich_enqueue(from_offset integer default 0, pages integer default 320, page_size integer default 1000)
returns integer
language plpgsql security definer
set search_path = public, extensions
as $$
declare i int; rid bigint; url text;
begin
  for i in 0..pages-1 loop
    url := 'https://maps2.vcgov.org/arcgis/rest/services/Pictometry_Parcels/MapServer/0/query'
      || '?where=1%3D1&outFields=OBJECTID,PARID,LANDSQFT,CALCACRES,LANDACRES,RES_MAX_STORIES,COM_MAX_STORIES,BLDGCOUNT,COM_BLDGCOUNT,LIVUNIT,COM_TOTALAREA,IMPRJUST,LANDJUST'
      || '&returnGeometry=false&orderByFields=OBJECTID&f=json'
      || '&resultOffset=' || (from_offset + i * page_size) || '&resultRecordCount=' || page_size;
    rid := net.http_get(url, timeout_milliseconds := 60000);
    insert into public.lot_enrich_queue (req_id, page_offset) values (rid, from_offset + i * page_size);
  end loop;
  return pages;
end;
$$;

create or replace function public.lot_enrich_process(max_pages integer default 50)
returns table(processed integer, patched integer, pending integer, failed integer)
language plpgsql security definer
set search_path = public, extensions
set statement_timeout = '600s'
as $$
declare q record; rows jsonb; n int; c_proc int := 0; c_patch int := 0;
begin
  for q in
    select lq.req_id, lq.page_offset, r.status_code, r.content, r.error_msg, r.timed_out
      from public.lot_enrich_queue lq
      join net._http_response r on r.id = lq.req_id
     where lq.processed_at is null
     order by lq.page_offset
     limit max_pages
  loop
    begin
      if q.status_code = 200 and q.content is not null then
        rows := public.lot_features_from_arcgis(q.content::jsonb);
        n := public.lot_features_apply(rows);
        update public.lot_enrich_queue set processed_at = now(), status_code = q.status_code,
               n_rows = jsonb_array_length(rows), n_patched = n where req_id = q.req_id;
        c_patch := c_patch + n;
      else
        update public.lot_enrich_queue set processed_at = now(), status_code = q.status_code,
               error = coalesce(q.error_msg, 'timeout=' || q.timed_out::text) where req_id = q.req_id;
      end if;
    exception when others then
      update public.lot_enrich_queue set processed_at = now(), error = sqlerrm where req_id = q.req_id;
    end;
    delete from net._http_response where id = q.req_id;
    c_proc := c_proc + 1;
  end loop;
  return query select c_proc, c_patch,
    (select count(*)::int from public.lot_enrich_queue where processed_at is null),
    (select count(*)::int from public.lot_enrich_queue where error is not null);
end;
$$;
